import { defineConfig } from 'vite';
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, sep } from 'node:path';

// After the build: write dist/sw.js that precaches every built file under a cache name derived from the file contents
// (a new build = a new cache; the old one is deleted on activate). Relative URLs, so it works in a subfolder.
function offlineSw() {
  let outDir = 'dist';
  return {
    name: 'lco-offline-sw',
    apply: 'build',
    configResolved(c) { outDir = c.build.outDir; },
    closeBundle() {
      const files = [];
      const walk = (d) => {
        for (const n of readdirSync(d)) {
          const f = join(d, n);
          if (statSync(f).isDirectory()) walk(f);
          else files.push(relative(outDir, f).replaceAll(sep, '/'));
        }
      };
      walk(outDir);
      const list = files.filter((f) => f !== 'sw.js' && f !== 'privacy.html').sort();
      const hash = createHash('sha1').update(list.join('|') + list.map((f) => statSync(join(outDir, f)).size).join(',')).digest('hex').slice(0, 10);
      const urls = ['./', ...list.filter((f) => f !== 'index.html')];
      writeFileSync(join(outDir, 'sw.js'), `// generated by vite.config.js: do not edit
const CACHE = 'lco-${hash}';
const URLS = ${JSON.stringify(urls)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(URLS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('lco-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const r = e.request;
  if (r.method !== 'GET' || new URL(r.url).origin !== location.origin) return; // fonts and ad scripts go straight to the network
  e.respondWith(caches.match(r, { ignoreSearch: true }).then((hit) => hit || fetch(r).catch(() => (r.mode === 'navigate' ? caches.match('./') : Response.error()))));
});
`);
    },
  };
}

// R11 fix 2: the share link, the code typed off a clip and its QR all use VITE_PUBLIC_URL; a release build without it
// falls back to whatever address serves the page, so say so once
function publicUrlNote() {
  return {
    name: 'lco-public-url',
    apply: 'build',
    configResolved(c) {
      const u = c.env && c.env.VITE_PUBLIC_URL;
      if (!u) c.logger.warn('[lco] VITE_PUBLIC_URL is not set: share links and QR codes will use the address the page is served from (RELEASE.md section 3).');
      else if (!/^https:\/\//.test(u)) c.logger.warn('[lco] VITE_PUBLIC_URL should be an https address: ' + u);
    },
  };
}

export default defineConfig({
  base: './',
  plugins: [offlineSw(), publicUrlNote()],
});
